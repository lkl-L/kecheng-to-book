CN = "一二三四五六七八九十"


def cn_num(n):
    if n <= 10:
        return CN[n - 1]
    if n < 20:
        return "十" + CN[n - 11]
    return CN[n // 10 - 1] + "十" + (CN[n % 10 - 1] if n % 10 else "")


def drop_block(lines, title, stop_at_sub=True):
    """删除以 title 开头的标题所在的整块。

    stop_at_sub=True ：块在小节/节标题处结束（删小节用）
    stop_at_sub=False：块在下一个节标题处才结束（删整节用，节内的小节一并删）
    """
    start = None
    for i, l in enumerate(lines):
        if l.strip() == title:
            start = i
            break
    if start is None:
        raise SystemExit("!! 未找到标题：%s" % title)
    end = len(lines)
    for j in range(start + 1, len(lines)):
        s = lines[j].strip()
        if SEC.match(s) or (stop_at_sub and SUB.match(s)):
            end = j
            break
    # 连同块尾的空行一起删
    while end - 1 > start and lines[end - 1].strip() == "":
        end -= 1
    return lines[:start] + lines[end:]


def renumber_subs(lines, section_title):
    """在 section_title 这一节的范围内，把小节号按顺序重排。"""
    start = None
    for i, l in enumerate(lines):
        if l.strip() == section_title:
            start = i
            break
    if start is None:
        raise SystemExit("!! 未找到节：%s" % section_title)
    end = len(lines)
    for j in range(start + 1, len(lines)):
        if SEC.match(lines[j].strip()):
            end = j
            break
    cnt = 0
    for k in range(start + 1, end):
        s = lines[k].strip()
        if SUB.match(s):
            cnt += 1
            body = s[s.index("）") + 1:]
            lines[k] = "（%s）%s" % (cn_num(cnt), body)
    return lines


def main():
    for name in sorted(set(list(DROP_SECTIONS) + list(DROP_SUBS) + list(PARA) +
                           list(RENAME) + list(RENUMBER) + list(RENUMBER_TEXT))):
        path = os.path.join("sec-md", name)
        lines = open(path, encoding="utf-8").read().replace("\r\n", "\n").split("\n")

        for t in DROP_SECTIONS.get(name, []):
            lines = drop_block(lines, t, stop_at_sub=False)
        for t in DROP_SUBS.get(name, []):
            lines = drop_block(lines, t, stop_at_sub=True)

        # 行级增删改
        for prefix, new in PARA.get(name, []):
            hit = 0
            for i, l in enumerate(lines):
                if l.startswith(prefix):
                    lines[i] = new
                    hit += 1
            if not hit:
                print("?? %s 未匹配行：%s" % (name, prefix[:30]))

        # 改名
        text = "\n".join(lines)
        for old, new in RENAME.get(name, []):
            if old not in text:
                print("?? %s 未找到：%s" % (name, old[:30]))
            text = text.replace(old, new)
        # 失据语句改写
        for old, new in RENUMBER_TEXT.get(name, []):
            if old not in text:
                print("?? %s 改写未命中：%s" % (name, old[:26]))
            text = text.replace(old, new)
        lines = text.split("\n")

        # 重编号
        for sec in RENUMBER.get(name, []):
            lines = renumber_subs(lines, sec)

        text = re.sub(r"\n{3,}", "\n\n", "\n".join(lines)).rstrip() + "\n"
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(text)

    # ===== 自检：正文里季节专章是否已清、季节词密度 =====
    print("=" * 46)
    for path in sorted(__import__("glob").glob("sec-md/bz-*.md")):
        t = open(path, encoding="utf-8").read()
        n = len(re.findall(r"季节|四时|节气|四季|月令|寒暖", t))
        if n >= 15:
            print("%-16s 季节类词 %3d 处" % (os.path.basename(path), n))
    print("=" * 46)
    # 关键标题确认
    for name in ["bz-002.md", "bz-003.md", "bz-004.md", "bz-010.md", "bz-012.md"]:
        t = open(os.path.join("sec-md", name), encoding="utf-8").read()
        hs = [l for l in t.split("\n") if SEC.match(l.strip())]
        print("%-14s %s" % (name, " | ".join(hs)))


if __name__ == "__main__":
    main()
