def main():
    files = sorted(glob.glob("sec-md/bz-*.md"))
    if len(files) != 22:
        print("!! 章节数不为 22：%d" % len(files))
    by_num = {}
    for f in files:
        m = re.search(r"bz-(\d+)\.md$", f)
        if m:
            by_num[int(m.group(1))] = f

    out = []
    out.append("# 《%s》" % BOOK)
    out.append("")
    out.append("理法体系入门读本 · 以阴阳五行与干支十神为主线")
    out.append("")
    out.append("—— 从阴阳五行到实战断命 ——")
    out.append("")
    out.append(INTRO)
    out.append("")
    out.append(INTRO2)
    out.append("")

    total = 0
    for vol_name, vol_note, nums in VOLUMES:
        out.append("## %s" % vol_name)
        out.append("")
        out.append(vol_note)
        out.append("")
        vn = 0
        for n in nums:
            p = by_num.get(n)
            if not p:
                print("!! 缺章节 bz-%03d" % n)
                continue
            t = open(p, encoding="utf-8").read().replace("\r\n", "\n").strip()
            lines = t.split("\n")
            # 首行 H2 标题 → H3
            head = lines[0]
            assert head.startswith("## "), "%s 首行不是 ## 标题" % p
            body = "\n".join(lines[1:]).strip()
            # 去掉可能残留的三级标题
            body = re.sub(r"^### .+$", "", body, flags=re.M).strip()
            out.append("### %s" % head[3:].strip())
            out.append("")
            out.append(body)
            out.append("")
            vn += len(re.sub(r"\s", "", body))
        print("%-24s %6d 字" % (vol_name, vn))
        total += vn

    # ===== 附录：命理要诀口诀 =====
    out.append("## 附　录")
    out.append("")
    out.append("正文之外，另将命理要诀口诀附录于后，以便诵读印证。")
    out.append("")
    out.append("### 附录　命理要诀口诀")
    out.append("")
    out.append(APP_NOTE)
    out.append("")
    for line in APPENDIX:
        out.append(line)
        out.append("")
    total += len(re.sub(r"\s", "", "".join(APPENDIX)))

    text = "\n".join(out).rstrip() + "\n"
    with open("%s.md" % BOOK, "w", encoding="utf-8") as fh:
        fh.write(text)
    print("-" * 40)
    print("全书正文合计 %d 字" % total)
    print("md 文件大小 %.1f KB" % (os.path.getsize("%s.md" % BOOK) / 1024))
    # 结构自检
    ls = text.split("\n")
    print("H1:%d H2:%d H3:%d" % (len([l for l in ls if l.startswith("# ")]),
                                 len([l for l in ls if l.startswith("## ")]),
                                 len([l for l in ls if l.startswith("### ")])))


if __name__ == "__main__":
    main()
